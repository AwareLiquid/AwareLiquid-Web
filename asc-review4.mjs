const CDP = "http://127.0.0.1:9222"
const list = await (await fetch(CDP + "/json/list")).json()
const page = list.find((t) => t.type === "page" && t.url.includes("appstoreconnect"))
const ws = new WebSocket(page.webSocketDebuggerUrl)
let id = 0
const pend = new Map()
ws.addEventListener("message", (ev) => {
  const m = JSON.parse(ev.data)
  if (m.id && pend.has(m.id)) {
    pend.get(m.id)(m)
    pend.delete(m.id)
  }
})
await new Promise((r) => ws.addEventListener("open", r))
const send = (method, params = {}) =>
  new Promise((res) => {
    const i = ++id
    const to = setTimeout(() => {
      pend.delete(i)
      res({ timeout: true })
    }, 25000)
    pend.set(i, (m) => {
      clearTimeout(to)
      res(m)
    })
    ws.send(JSON.stringify({ id: i, method, params }))
  })
const sleep = (ms) => new Promise((r) => setTimeout(r, ms))
const evalV = async (expr) => {
  const r = await send("Runtime.evaluate", { expression: expr, returnByValue: true })
  return r.timeout ? "TIMEOUT" : r.result.result?.value
}

const href = await evalV(`(() => { const a = [...document.querySelectorAll('a')].find(x => /reviewsubmissions\\/details/.test(x.getAttribute('href')||'')); return a ? a.href : null })()`)
console.log("href:", href)
if (!href) process.exit(0)
await send("Page.navigate", { url: href })
await sleep(12000)
const t = await evalV(`document.body.innerText`)
const idx = t.indexOf("Messages")
console.log("TEXT:", JSON.stringify(t.slice(Math.max(0, idx - 300), idx + 2600)))
ws.close()
